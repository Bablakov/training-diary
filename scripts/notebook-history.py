NOW = int(datetime.now().timestamp() * 1000)
BASE = {"Жим лёжа", "Становая тяга", "Присед"}


def ts(date, hm):
    if not hm:
        return None
    return int(datetime.strptime(f"{date} {hm}", "%Y-%m-%d %H:%M").timestamp() * 1000)


def S(w, r, m=0, n="", done=True, drops=()):
    return {"pw": "", "pr": "", "pl": "", "w": "" if w is None else str(w), "r": "" if r is None else str(r), "m": m, "n": n,
            "done": done, "t": None, "prev": None, "drops": [{"pw": "", "w": "" if a is None else str(a), "r": str(b)} for a, b in drops]}


def plan(sets, reps=""):
    return {"sets": [{"w": str(w), "r": str(r), "l": l} for w, r, l in sets], "reps": reps, "mode": "same"}


def same(w, r, n):
    return [(w, r, "")] * n


def item(date, k, name, plan_sets, start, sets, note="", reps="", names=None):
    return {"id": f"{date}-{k}", "kind": "combo" if names else "ex", "name": name, "names": names or [],
            "base": name in BASE, "plan": plan(plan_sets, reps), "pnote": "", "note": note,
            "start": ts(date, start), "end": None, "sets": sets}


def session(date, title, pid, bw, start, end, warm, note, items, time_unknown=False):
    st = ts(date, start)
    return {"id": f"nb-{date}", "programId": pid, "planId": None, "title": title, "gymId": None,
            "start": st, "end": st if time_unknown else ts(date, end), "timeUnknown": time_unknown,
            "bodyWeight": bw, "note": note, "upd": NOW, "feel": {"before": 0, "after": 0},
            "warm": {"n": 3, "done": 3, "start": ts(date, warm), "end": None, "skipped": False},
            "items": [item(date, k, *it[:5], **(it[5] if len(it) > 5 else {})) for k, it in enumerate(items)]}


